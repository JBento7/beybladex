// Generates prisma/migrations/20261028000050_schema_compat/migration.sql from
// the additive DDL list in src/app/api/migrate/route.ts (single source).
// Every statement is idempotent (IF NOT EXISTS / duplicate_object guards), so
// on a database created by the baseline it is a no-op, and on an existing
// database it only ADDS what is missing — it never drops or rewrites data.
//   node scripts/gen-compat-migration.mjs          (write)
//   node scripts/gen-compat-migration.mjs --check  (fail if out of date)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const route = readFileSync(new URL("../src/app/api/migrate/route.ts", import.meta.url), "utf8");
const stmts = [...route.matchAll(/name: "([^"]+)",\s*sql: `([\s\S]*?)`/g)].map(([, name, sql]) => ({ name, sql: sql.trim() }));
for (const s of stmts) {
  if (s.sql.includes("${")) throw new Error(`template expression in ${s.name}`);
  if (/^\s*(UPDATE|DELETE|TRUNCATE|DROP)\b/i.test(s.sql) || /\bDROP\s+(TABLE|COLUMN)\b/i.test(s.sql)) throw new Error(`not additive: ${s.name}`);
}
// /api/migrate ignores each failing statement; a migration aborts. So every
// statement tolerates ONLY "already exists" (duplicate object/table/column) —
// any other error still stops the migration.
const DUP = "duplicate_object OR duplicate_table OR duplicate_column";
function guarded(sql) {
  const body = sql.replace(/;\s*$/, "");
  if (/^DO \$\$/.test(body)) return body.replace(/EXCEPTION WHEN duplicate_object THEN null/gi, `EXCEPTION WHEN ${DUP} THEN null`);
  if (body.includes("$q$")) throw new Error("unexpected $q$ in statement");
  return `DO $lbl$ BEGIN EXECUTE $q$${body}$q$; EXCEPTION WHEN ${DUP} THEN NULL; END $lbl$`;
}
const out = [
  "-- Generated by scripts/gen-compat-migration.mjs — do not edit by hand.",
  "-- Additive, idempotent schema compatibility for databases that predate the",
  "-- versioned migrations (they were kept up to date by /api/migrate).",
  "",
  ...stmts.map((s) => `-- ${s.name}\n${guarded(s.sql)};\n`),
].join("\n");
const dir = new URL("../prisma/migrations/20261028000050_schema_compat/", import.meta.url);
const file = new URL("migration.sql", dir);
if (process.argv.includes("--check")) {
  const cur = readFileSync(file, "utf8");
  if (cur !== out) { console.error("schema_compat migration is out of date: run node scripts/gen-compat-migration.mjs"); process.exit(1); }
  console.log(`ok (${stmts.length} statements)`);
} else {
  mkdirSync(dir, { recursive: true });
  writeFileSync(file, out);
  console.log(`wrote ${stmts.length} statements`);
}
